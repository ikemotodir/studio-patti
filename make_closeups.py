RECTS = {}


def scene():
    im = Image.new("RGB", (W, H), P['n1'])
    return im, ImageDraw.Draw(im)


def R(d, x, y, w, h, c):
    d.rectangle([x, y, x + w - 1, y + h - 1], fill=P[c])


def O(d, x, y, w, h, fill, out):
    R(d, x, y, w, h, out); R(d, x + 1, y + 1, w - 2, h - 2, fill)


def dith(d, x, y, w, h, c, den=2, ph=0):
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            if (xx + yy + ph) % den == 0:
                d.point((xx, yy), fill=P[c])


def PXL(d, x, y, c):
    d.point((x, y), fill=P[c])


def vignette(d, base='n1', dark='n0'):
    dith(d, 0, 0, W, 14, dark, 2)
    dith(d, 0, H - 14, W, 14, dark, 2, 1)
    dith(d, 0, 0, 12, H, dark, 2)
    dith(d, W - 12, 0, 12, H, dark, 2, 1)


def save(im, key, content_rect):
    im.save(os.path.join(WEB, f"closeup_{key}.png"))
    RECTS[key] = content_rect
    print("closeup_" + key, content_rect)


